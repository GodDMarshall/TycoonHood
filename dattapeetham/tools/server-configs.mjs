/**
 * _redirects in the syntax Netlify and Cloudflare share: "from to status",
 * fixed paths first (Cloudflare counts every rule after the first splat as
 * dynamic, and allows 100). `netlifyForce` appends "!" to the page-URL rules
 * so Netlify applies them even though it could serve /about from about.html;
 * Cloudflare rejects "301!", so that file is Netlify-only.
 */
export function renderRedirects(m, { netlifyForce = false } = {}) {
  const L = [intro(m, 'Avadhoota Datta Peetham website: _redirects (Netlify, Cloudflare).'), ''];
  const line = (from, to, status) => L.push(`${from.padEnd(70)} ${to.padEnd(46)} ${status}`);
  L.push(`# Old-site URLs → new pages (query strings are passed on by both hosts).`);
  for (const r of oldSite(m)) line(r.from, r.to, r.status);
  L.push('',
    '# Folder index pages. Needed on Cloudflare with html_handling "none" (see',
    '# deploy/cloudflare/wrangler.jsonc); Netlify serves these itself and skips them.');
  for (const r of ['', ...m.languages.map((l) => `/${l}`)]) line(`${r}/`, `${r}/index.html`, 200);
  L.push('', '# Page URLs without .html → the canonical .html URL. Never forced: /kn → /kn/');
  L.push('# would loop on Netlify, which matches /kn and /kn/ alike (it skips the rule');
  L.push('# because /kn/ exists, and adds the slash itself).');
  for (const r of pageRules(m)) line(r.from, r.to, `${r.status}${netlifyForce && r.kind !== 'language-root' ? '!' : ''}`);
  if (m.platform) {
    L.push('', `# The Peetham's existing platform → ${m.platform.origin} (${m.platform.status}: it may move again).`);
    for (const p of m.platform.paths) line(p, `${m.platform.origin}${p}`, m.platform.status);
    for (const p of m.platform.paths) line(`${p}/*`, `${m.platform.origin}${p}/:splat`, m.platform.status);
    for (const p of m.platform.prefixes) line(`${p}*`, `${m.platform.origin}${p}:splat`, m.platform.status);
  } else {
    L.push('', '# Platform paths: none. The platform shares this host; see site.config.json.');
  }
  L.push('');
  return L.join('\n');
}

/**
 * _headers: security headers on every path; long-lived Cache-Control only on
 * the asset folders that earn it. Both hosts apply every matching rule and
 * Cloudflare appends a second value to the first, so Cache-Control is never
 * set on /* (pages and JSON keep the hosts' default "public, max-age=0,
 * must-revalidate", which revalidates like "no-cache"). Cloudflare allows
 * 100 rules.
 */
export function renderHeaders(m) {
  const L = [intro(m, 'Avadhoota Datta Peetham website: _headers (Netlify, Cloudflare).'), '', '/*'];
  for (const [k, v] of Object.entries(m.headers)) L.push(`  ${k}: ${v}`);
  for (const g of m.assetGroups) L.push('', g.path, `  Cache-Control: ${g.value}`);
  L.push('');
  return L.join('\n');
}

