#!/usr/bin/env node
// Server configuration for every common host, generated from one set of rules
// (deploy/routes.mjs) so the site behaves the same wherever it is served.
//
//   node tools/server-configs.mjs <siteDir> [--site-url=https://…] [--legacy-url=https://…]
//                                           [--netlify-force] [--no-project-files | --project-files=<dir>]
//
// Each address comes from its flag, else DP_SITE_URL / DP_LEGACY_URL, else
// site.config.json (siteUrl, legacyPlatformUrl), else https://www.dattapeetham.org.
//
// Writes into <siteDir> (it travels with the site):
//   .htaccess      Apache 2.4, cPanel and most shared hosting
//   _headers       Netlify, Cloudflare (Pages and Workers static assets)
//   _redirects     Netlify, Cloudflare
//   web.config     IIS (URL Rewrite module)
//   .assetsignore  Cloudflare Workers: keeps the other servers' files private
// and into the project (skip with --no-project-files):
//   deploy/nginx/dattapeetham.conf      nginx server blocks, TLS-ready
//   deploy/cloudflare/wrangler.jsonc    Cloudflare Workers static assets
//   vercel.json                         Vercel
//
// The build calls writeServerConfigs() after it writes the pages. A build into
// ./site also rewrites the project files for the addresses it used (flags,
// environment or site.config.json); a build elsewhere (--out=…) leaves them.

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync, readFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as R from '../deploy/routes.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DEFAULT_URL = 'https://www.dattapeetham.org';
export const PROJECT_FILES = {
  nginx: join(ROOT, 'deploy', 'nginx', 'dattapeetham.conf'),
  wrangler: join(ROOT, 'deploy', 'cloudflare', 'wrangler.jsonc'),
  vercel: join(ROOT, 'vercel.json'),
};
const GENERATED = `Generated by tools/server-configs.mjs from deploy/routes.mjs (v${R.VERSION}).`;
const DO_NOT_EDIT = 'Do not edit by hand: change deploy/routes.mjs or site.config.json, then run\n  node tools/server-configs.mjs site\n(the build runs it too).';

// ---------------------------------------------------------------- inputs ---

/** A bare http(s) origin: no path, query or fragment. */
export function toOrigin(value, name = 'URL') {
  const raw = String(value ?? '').trim();
  let u;
  try { u = new URL(raw); } catch { throw new Error(`${name} "${raw}" is not an absolute URL (for example ${DEFAULT_URL})`); }
  if (!/^https?:$/.test(u.protocol)) throw new Error(`${name} "${raw}" must start with https://`);
  if (u.username || u.password || u.search || u.hash || /[?#]/.test(raw) || u.pathname.replace(/\/+$/, '')) {
    throw new Error(`${name} "${raw}" must be a bare address such as ${DEFAULT_URL}, with no path, query or fragment`);
  }
  return u.origin;
}

/**
 * siteUrl and legacyUrl, each resolved on its own like the build does:
 * --site-url= / --legacy-url=, then DP_SITE_URL / DP_LEGACY_URL, then
 * site.config.json (siteUrl, legacyPlatformUrl), then ${DEFAULT_URL}.
 */
export function resolveAddresses({ argv = [], env = process.env, file = join(ROOT, 'site.config.json') } = {}) {
  let json = {};
  try { json = JSON.parse(readFileSync(file, 'utf8')); } catch { /* no file: defaults */ }
  const flag = (name) => { const a = argv.find((x) => x.startsWith(`--${name}=`)); return a ? a.slice(name.length + 3) : undefined; };
  return {
    siteUrl: flag('site-url') || env.DP_SITE_URL || json.siteUrl || DEFAULT_URL,
    legacyUrl: flag('legacy-url') || env.DP_LEGACY_URL || json.legacyPlatformUrl || json.legacyUrl || DEFAULT_URL,
  };
}

async function walk(dir, base = '') {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true }).catch(() => [])) {
    const rel = base ? `${base}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...(await walk(join(dir, e.name), rel)));
    else out.push(rel);
  }
  return out;
}

/** What the generator needs to know about a built site. */
export async function scanSite(siteDir) {
  const files = await walk(siteDir);
  const pages = files.filter((f) => /^[^/]+\.html$/.test(f)).sort();
  const langs = R.LANGUAGES.filter((l) => files.includes(`${l}/index.html`));
  const html = files.filter((f) => f.endsWith('.html'));
  const js = files.filter((f) => /^assets\/.+\.m?js$/.test(f));
  const text = new Map();
  for (const f of [...html, ...js]) text.set(f, await readFile(join(siteDir, f), 'utf8'));
  return { files, pages, langs, assets: files.filter((f) => f.startsWith('assets/')).map((f) => '/' + f), text };
}

const CODE_REF = /(?:^|\/)assets\/[^"'`?#\s]+\.(?:css|m?js)(?:[?#][^"'`\s]*)?$/i;
const isVersioned = (url) => /[?&]v=[^&#]+/.test(url) || /[.-][0-9a-f]{8,}\.(?:css|m?js)(?:[?#]|$)/i.test(url);

/**
 * Are the site's own CSS/JS files referenced by content hash everywhere?
 * Only then may they be cached as immutable. Looks at every <script src> and
 * <link href> in the pages, plus asset paths written as string literals in
 * the scripts (files a script loads itself).
 */
export function detectVersioning(text) {
  const refs = [];
  for (const [file, src] of text) {
    const found = file.endsWith('.html')
      ? [...src.matchAll(/<(?:script\b[^>]*?\ssrc|link\b[^>]*?\shref)="([^"]+)"/g)].map((m) => m[1].replace(/&amp;/g, '&'))
      : [...src.matchAll(/["'`]((?:\.\.\/)*assets\/[^"'`\s]+?\.(?:css|m?js)(?:\?[^"'`\s]*)?)["'`]/g)].map((m) => m[1]);
    for (const url of found) {
      if (/^(?:[a-z][a-z0-9+.-]*:|\/\/)/i.test(url) || !CODE_REF.test(url)) continue;
      refs.push({ file, url, versioned: isVersioned(url) });
    }
  }
  const unversioned = refs.filter((r) => !r.versioned);
  return { versioned: refs.length > 0 && unversioned.length === 0, total: refs.length, unversioned: unversioned.slice(0, 5) };
}

// ----------------------------------------------------------------- model ---

const matchesRule = (path, rule) => path.startsWith(rule.prefix) && rule.extensions.some((x) => path.toLowerCase().endsWith('.' + x));
export const cacheFor = (path, rules) => (rules.find((r) => matchesRule(path, r)) || { value: R.defaultCache }).value;

/**
 * Collapse per-file cache values into as few path rules as possible, for
 * servers that match by path prefix only (_headers, IIS <location>): a folder
 * whose files all share one value gets one rule; mixed folders are split.
 * Files with the default value need no rule.
 */
export function groupAssets(paths, rules) {
  const tree = { dirs: new Map(), files: [] };
  for (const p of paths) {
    const parts = p.split('/').filter(Boolean);
    let node = tree;
    for (const d of parts.slice(0, -1)) {
      if (!node.dirs.has(d)) node.dirs.set(d, { dirs: new Map(), files: [] });
      node = node.dirs.get(d);
    }
    node.files.push(p);
  }
  const all = (n) => [...n.files, ...[...n.dirs.values()].flatMap(all)];
  const out = [];
  const visit = (node, prefix) => {
    const values = new Set(all(node).map((f) => cacheFor(f, rules)));
    if (values.size === 1) {
      const [value] = values;
      if (value !== R.defaultCache) out.push({ path: `${prefix}/*`, dir: prefix, value });
      return;
    }
    for (const f of node.files.sort()) if (cacheFor(f, rules) !== R.defaultCache) out.push({ path: f, file: f, value: cacheFor(f, rules) });
    for (const [name, child] of [...node.dirs].sort()) visit(child, `${prefix}/${name}`);
  };
  for (const [name, child] of [...tree.dirs].sort()) visit(child, `/${name}`);
  for (const f of tree.files.sort()) if (cacheFor(f, rules) !== R.defaultCache) out.push({ path: f, file: f, value: cacheFor(f, rules) });
  return out;
}

/** The fragment id of a redirect target exists on the target page. */
function checkTargets(redirects, scan, problems) {
  if (!scan) return;
  for (const r of redirects) {
    const [path, hash] = r.to.split('#');
    const file = path.endsWith('/') ? `${path.slice(1)}index.html` : path.slice(1);
    const html = scan.text.get(file);
    if (html === undefined) { problems.push(`redirect ${r.from} → ${r.to}: ${file} is not in the built site`); continue; }
    if (hash && !new RegExp(`\\sid="${hash.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"`).test(html)) problems.push(`redirect ${r.from} → ${r.to}: ${file} has no id="${hash}"`);
  }
}

/**
 * Everything every renderer needs, resolved once: absolute addresses, the
 * full ordered redirect list, the platform rules (or null), cache rules.
 */
export async function buildModel({ siteDir, siteUrl = DEFAULT_URL, legacyUrl = siteUrl, pages, langs, versionedAssets, scan } = {}) {
  const site = new URL(toOrigin(siteUrl, 'siteUrl'));
  const legacy = new URL(toOrigin(legacyUrl, 'legacyUrl'));
  scan ??= siteDir ? await scanSite(siteDir) : null;
  const files = (pages ? pages.map((p) => (typeof p === 'string' ? p : p.file)) : scan?.pages || []).filter((f) => f && /^[^/]+\.html$/.test(f));
  if (!files.length) throw new Error('server-configs: no pages (pass `pages`, or a siteDir holding the built site)');
  const names = [...new Set(files)].filter((f) => f !== 'index.html' && !R.pageUrls.exclude.includes(f)).map((f) => f.slice(0, -5)).sort();
  const languages = langs || (scan ? scan.langs : R.LANGUAGES);
  const versioning = versionedAssets !== undefined
    ? { versioned: Boolean(versionedAssets), total: 0, unversioned: [], forced: true }
    : scan ? detectVersioning(scan.text) : { versioned: false, total: 0, unversioned: [] };

  const status = R.REDIRECT_STATUS;
  const redirects = R.oldSiteRedirects.map(([from, to]) => ({ from, to, status, kind: 'old-site' }));
  const roots = ['', ...languages.map((l) => `/${l}`)];
  for (const r of roots) redirects.push({ from: `${r}/index`, to: `${r}/`, status: R.pageUrls.status, kind: 'index' });
  for (const l of languages) redirects.push({ from: `/${l}`, to: `/${l}/`, status: R.pageUrls.status, kind: 'language-root' });
  for (const r of roots) for (const n of names) redirects.push({ from: `${r}/${n}`, to: `${r}/${n}.html`, status: R.pageUrls.status, kind: 'page' });

  const problems = [];
  const warnings = [];
  const seen = new Set();
  for (const r of redirects) {
    if (seen.has(r.from)) problems.push(`two redirects for ${r.from}`);
    seen.add(r.from);
    if (files.includes(r.from.slice(1))) problems.push(`redirect source ${r.from} is a page of the site`);
  }
  checkTargets(redirects.filter((r) => r.kind === 'old-site'), scan, problems);

  const splitHost = site.host !== legacy.host;
  let platform = null;
  if (splitHost) {
    platform = { origin: legacy.origin, status: R.legacyPlatform.status, paths: [...R.legacyPlatform.paths], prefixes: [...R.legacyPlatform.prefixes] };
    for (const p of platform.paths) {
      if (seen.has(p)) problems.push(`platform path ${p} is also redirected to a page (remove one)`);
      if (!/^\/[a-z0-9-]+(?:\/[a-z0-9-]+)*$/.test(p)) problems.push(`platform path ${p} must be a plain /path`);
    }
    for (const p of platform.prefixes) if (!/^\/[a-z0-9/-]+\/$/.test(p)) problems.push(`platform prefix ${p} must look like /path/`);
    if (site.host.replace(/^www\./, '') === legacy.host.replace(/^www\./, '')) {
      warnings.push(`the platform (${legacy.host}) and the site (${site.host}) differ only by "www.": if one name redirects to the other, platform links will loop`);
    }
  }
  if (!versioning.versioned && !versioning.forced) {
    warnings.push(versioning.total
      ? `CSS/JS are not all referenced by content hash (e.g. ${versioning.unversioned.map((u) => `${u.file}: ${u.url}`).join(', ')}): they get "${R.defaultCache}" instead of a one-year immutable cache`
      : `no versioned CSS/JS references found: CSS/JS get "${R.defaultCache}"`);
  }
  if (problems.length) throw new Error('server-configs: the routes do not fit the built site:\n  ' + problems.join('\n  '));

  const cache = R.cacheRules.filter((r) => !r.versionedOnly || versioning.versioned).map(({ name, prefix, extensions, value }) => ({ name, prefix, extensions, value }));
  const host = site.hostname;
  return {
    version: R.VERSION,
    siteUrl: site.origin,
    legacyUrl: legacy.origin,
    canonicalHost: host,
    hostAlias: host.startsWith('www.') ? host.slice(4) : `www.${host}`,
    https: site.protocol === 'https:',
    splitHost,
    languages,
    pages: names,
    redirects,
    platform,
    headers: { ...R.securityHeaders },
    cache,
    defaultCache: R.defaultCache,
    assetGroups: scan ? groupAssets(scan.assets, cache) : [],
    versioning,
    contentTypes: { ...R.contentTypes },
    notFound: R.NOT_FOUND_PAGE,
    warnings,
  };
}

// --------------------------------------------------------------- helpers ---

const reEsc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const xml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const splitHash = (to) => { const i = to.indexOf('#'); return i < 0 ? [to, ''] : [to.slice(0, i), to.slice(i)]; };
const extGroup = (exts) => `(?:${exts.map(reEsc).join('|')})`;
const pageAlternation = (m) => m.pages.map(reEsc).join('|');
const langAlternation = (m) => m.languages.map(reEsc).join('|');
const platformAlternation = (m) => m.platform.paths.map((p) => reEsc(p.slice(1))).join('|');
const prefixAlternation = (m) => m.platform.prefixes.map((p) => reEsc(p.slice(1, -1))).join('|');
const comment = (text, mark = '#') => text.split('\n').map((l) => (l ? `${mark} ${l}` : mark)).join('\n');
const intro = (m, what) => comment(`${what}\n${GENERATED}\n${DO_NOT_EDIT}\n\n  site:             ${m.siteUrl}\n  legacy platform:  ${m.legacyUrl}${m.splitHost ? '' : '  (same host: no platform redirects, they would loop)'}`);
const oldSite = (m) => m.redirects.filter((r) => r.kind === 'old-site');
const pageRules = (m) => m.redirects.filter((r) => r.kind !== 'old-site');

// ---------------------------------------------------------------- Apache ---

// The original request line ("GET /.well-known/acme-challenge/x HTTP/1.1",
// also in absolute form) does not name a certificate path. Unlike REQUEST_URI,
// THE_REQUEST keeps its value in the internal request ErrorDocument makes.
const ACME_REQUEST_LINE = '!^[A-Z]+\\s+(?:[a-z][a-z0-9+.-]*://[^/\\s]*)?/\\.well-known/(?:acme-challenge|pki-validation)/ [NC]';

export function renderHtaccess(m) {
  const L = [];
  const push = (...x) => L.push(...x);
  const host = reEsc(m.canonicalHost);
  const alias = reEsc(m.hostAlias);
  push(intro(m, 'Avadhoota Datta Peetham website: Apache 2.4 (cPanel and most shared hosting).'),
    '#',
    '# Needs AllowOverride All on the document root (cPanel default). Uses',
    '# mod_rewrite, mod_headers, mod_mime, mod_dir; mod_deflate / mod_brotli when',
    '# present. Every module block is guarded, so a missing module degrades a',
    '# feature instead of breaking the site. deploy/apache/ has the server side.',
    '',
    'DirectoryIndex index.html',
    `ErrorDocument 404 ${m.notFound}`,
    'AddDefaultCharset utf-8',
    '',
    '# No directory listings. No content negotiation: /about must redirect to',
    '# /about.html, not quietly serve it.',
    'Options -Indexes -MultiViews',
    '',
    '<IfModule mod_mime.c>');
  for (const [ext, type] of Object.entries(m.contentTypes)) push(`  AddType ${type} .${ext}`);
  push('  AddCharset utf-8 .css .js .mjs .json .webmanifest .svg .xml .txt',
    '</IfModule>',
    '',
    '# ---- compression ---------------------------------------------------------');
  const types = 'text/html text/css text/javascript application/javascript application/json application/manifest+json application/xml text/xml image/svg+xml text/plain';
  push('<IfModule mod_filter.c>',
    '  <IfModule mod_brotli.c>',
    `    AddOutputFilterByType BROTLI_COMPRESS ${types}`,
    '  </IfModule>',
    '  <IfModule mod_deflate.c>',
    `    AddOutputFilterByType DEFLATE ${types}`,
    '  </IfModule>',
    '</IfModule>',
    '',
    '# ---- caching -------------------------------------------------------------',
    '# The Cache-Control headers below are the whole policy. A host-wide',
    '# "ExpiresActive On" would add a second, conflicting max-age, so mod_expires',
    '# is switched off for this site.',
    '<IfModule mod_expires.c>',
    '  ExpiresActive Off',
    '</IfModule>',
    '',
    '<IfModule mod_headers.c>',
    `  Header always set Cache-Control "${m.defaultCache}"`);
  m.cache.forEach((rule, i) => {
    push(`  <${i ? 'ElseIf' : 'If'} "%{REQUEST_URI} =~ m#^${reEsc(rule.prefix)}.+\\.${extGroup(rule.extensions)}$#i">`,
      `    # ${rule.name}`,
      `    Header always set Cache-Control "${rule.value}"`,
      `  </${i ? 'ElseIf' : 'If'}>`);
  });
  push('',
    '  # ---- security headers (every response, redirects and errors included) ---');
  for (const [k, v] of Object.entries(m.headers)) push(`  Header always set ${k} "${v.replace(/"/g, '\\"')}"`);
  push('  Header always unset X-Powered-By',
    '</IfModule>',
    '',
    '# ---- redirects -------------------------------------------------------------',
    '<IfModule mod_rewrite.c>',
    '  RewriteEngine On',
    '  # mod_rewrite in .htaccess needs symlink following. If your host refuses',
    '  # this line (500 error), delete it: most hosts already allow it.',
    '  Options +SymLinksIfOwnerMatch',
    '');
  if (m.https) {
    push('  # ==== BEGIN canonical host and HTTPS ========================================',
      `  # Sends ${m.hostAlias} and plain http:// to https://${m.canonicalHost}.`,
      '  # Other host names (a staging or cPanel preview address, the server IP) are',
      '  # left alone. To switch this block off, delete it, or add to the virtual',
      '  # host:  SetEnvIf Request_URI "^" DP_CANONICAL=off',
      '  # Behind a proxy or CDN that ends TLS, it trusts X-Forwarded-Proto: https.',
      '  # The certificate paths are checked in the request line as well: a missing',
      '  # challenge file triggers ErrorDocument, whose internal request for the 404',
      '  # page would otherwise be redirected to https (a 301 instead of a 404).',
      '  RewriteCond %{ENV:DP_CANONICAL} !=off',
      '  RewriteCond %{REQUEST_URI} !^/\\.well-known/(?:acme-challenge|pki-validation)/',
      `  RewriteCond %{THE_REQUEST} ${ACME_REQUEST_LINE}`,
      `  RewriteCond %{HTTP_HOST} ^${alias}\\.?(?::\\d+)?$ [NC]`,
      `  RewriteRule ^ https://${m.canonicalHost}%{REQUEST_URI} [R=301,L]`,
      '  RewriteCond %{ENV:DP_CANONICAL} !=off',
      '  RewriteCond %{REQUEST_URI} !^/\\.well-known/(?:acme-challenge|pki-validation)/',
      `  RewriteCond %{THE_REQUEST} ${ACME_REQUEST_LINE}`,
      `  RewriteCond %{HTTP_HOST} ^${host}\\.?(?::\\d+)?$ [NC]`,
      '  RewriteCond %{HTTPS} !=on',
      '  RewriteCond %{HTTP:X-Forwarded-Proto} !^https$ [NC]',
      `  RewriteRule ^ https://${m.canonicalHost}%{REQUEST_URI} [R=301,L]`,
      '  # ==== END canonical host and HTTPS ==========================================',
      '');
  }
  push('  # Hidden files (except /.well-known/) and the other servers\' config files.',
    '  RewriteRule (?:^|/)\\.(?!well-known(?:/|$)) - [R=404,L]',
    '  RewriteRule ^(?:_headers|_redirects|web\\.config)$ - [R=404,L]',
    '',
    `  # Old-site URLs → new pages (${R.REDIRECT_STATUS}). The query string is kept; a #fragment`,
    '  # goes after it, so those rules come in pairs.');
  for (const r of oldSite(m)) {
    const [path, hash] = splitHash(r.to);
    const src = `^${reEsc(r.from.slice(1))}$`;
    if (!hash) { push(`  RewriteRule ${src} ${path} [R=${r.status},L]`); continue; }
    push('  RewriteCond %{QUERY_STRING} =""',
      `  RewriteRule ${src} ${path}${hash} [R=${r.status},NE,L]`,
      `  RewriteRule ${src} ${path}?%{QUERY_STRING}${hash} [R=${r.status},NE,L]`);
  }
  const langs = m.languages.length ? `(?:(?:${langAlternation(m)})/)?` : '';
  push('',
    '  # Page URLs without .html → the canonical .html URL.',
    `  RewriteRule ^(${langs})index$ /$1 [R=${R.pageUrls.status},L]`);
  if (m.languages.length) push(`  RewriteRule ^(${langAlternation(m)})$ /$1/ [R=${R.pageUrls.status},L]`);
  push(`  RewriteRule ^(${langs}(?:${pageAlternation(m)}))$ /$1.html [R=${R.pageUrls.status},L]`, '');
  if (m.platform) {
    push(`  # The Peetham's existing platform → ${m.platform.origin} (${m.platform.status}: it may move again).`,
      `  RewriteRule ^(?:${platformAlternation(m)})(?:/.*)?$ ${m.platform.origin}%{REQUEST_URI} [R=${m.platform.status},L]`,
      `  RewriteRule ^(?:${prefixAlternation(m)})/. ${m.platform.origin}%{REQUEST_URI} [R=${m.platform.status},L]`,
      '');
  } else {
    push('  # Platform paths: none. The platform shares this host; see site.config.json.', '');
  }
  push('  # A folder without an index page is "not found", not "forbidden".',
    '  RewriteCond %{REQUEST_FILENAME} -d',
    '  RewriteCond %{REQUEST_FILENAME}/index.html !-f',
    '  RewriteRule ^ - [R=404,L]',
    '</IfModule>',
    '',
    '# Without mod_rewrite, at least keep hidden files private.',
    '<IfModule !mod_rewrite.c>',
    '  <FilesMatch "^\\.">',
    '    Require all denied',
    '  </FilesMatch>',
    '</IfModule>',
    '');
  return L.join('\n');
}

