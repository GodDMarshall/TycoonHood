export function renderWebConfig(m) {
  const L = [];
  const push = (...x) => L.push(...x);
  const redirect = (url, type, append) => `<action type="Redirect" url="${xml(url)}" redirectType="${type}" appendQueryString="${append}" />`;
  const type = (s) => ({ 301: 'Permanent', 302: 'Found', 303: 'SeeOther', 307: 'Temporary' }[s] || 'Permanent');
  push('<?xml version="1.0" encoding="utf-8"?>',
    '<!--',
    intro(m, 'Avadhoota Datta Peetham website: IIS 7.5+ (needs the URL Rewrite module).').replace(/--/g, '- -').split('\n').map((l) => '  ' + l.replace(/^# ?/, '')).join('\n'),
    '-->',
    '<configuration>',
    '  <system.webServer>',
    '    <defaultDocument enabled="true">',
    '      <files>',
    '        <clear />',
    '        <add value="index.html" />',
    '      </files>',
    '    </defaultDocument>',
    '    <directoryBrowse enabled="false" />',
    '    <staticContent>',
    '      <clientCache cacheControlMode="NoControl" />');
  for (const [ext, t] of Object.entries(m.contentTypes)) push(`      <remove fileExtension=".${ext}" />`, `      <mimeMap fileExtension=".${ext}" mimeType="${xml(t)}" />`);
  push('    </staticContent>',
    '    <httpProtocol>',
    '      <customHeaders>',
    '        <remove name="X-Powered-By" />');
  for (const [k, v] of Object.entries(m.headers)) push(`        <remove name="${xml(k)}" />`, `        <add name="${xml(k)}" value="${xml(v)}" />`);
  push('        <remove name="Cache-Control" />',
    `        <add name="Cache-Control" value="${xml(m.defaultCache)}" />`,
    '      </customHeaders>',
    '    </httpProtocol>',
    '    <httpErrors errorMode="Custom" existingResponse="Replace">',
    '      <remove statusCode="404" subStatusCode="-1" />',
    `      <error statusCode="404" path="${xml(m.notFound)}" responseMode="ExecuteURL" />`,
    '    </httpErrors>',
    '    <security>',
    '      <requestFiltering>',
    '        <hiddenSegments>',
    '          <add segment=".htaccess" />',
    '          <add segment=".assetsignore" />',
    '          <add segment="_headers" />',
    '          <add segment="_redirects" />',
    '        </hiddenSegments>',
    '      </requestFiltering>',
    '    </security>',
    '    <rewrite>',
    '      <rules>');
  if (m.https) {
    const host = reEsc(m.canonicalHost);
    const alias = reEsc(m.hostAlias);
    push('        <!-- ==== BEGIN canonical host and HTTPS: set enabled="false" on both rules to switch off ==== -->',
      `        <rule name="DP canonical host" enabled="true" stopProcessing="true">`,
      '          <match url=".*" />',
      '          <conditions logicalGrouping="MatchAll">',
      `            <add input="{HTTP_HOST}" pattern="^${xml(alias)}\\.?(?::\\d+)?$" />`,
      '            <add input="{REQUEST_URI}" pattern="^/\\.well-known/(?:acme-challenge|pki-validation)/" negate="true" />',
      '          </conditions>',
      `          ${redirect(`https://${m.canonicalHost}{REQUEST_URI}`, 'Permanent', false)}`,
      '        </rule>',
      `        <rule name="DP https" enabled="true" stopProcessing="true">`,
      '          <match url=".*" />',
      '          <conditions logicalGrouping="MatchAll">',
      `            <add input="{HTTP_HOST}" pattern="^${xml(host)}\\.?(?::\\d+)?$" />`,
      '            <add input="{HTTPS}" pattern="^OFF$" />',
      '            <add input="{HTTP_X_FORWARDED_PROTO}" pattern="^https$" negate="true" />',
      '            <add input="{REQUEST_URI}" pattern="^/\\.well-known/(?:acme-challenge|pki-validation)/" negate="true" />',
      '          </conditions>',
      `          ${redirect(`https://${m.canonicalHost}{REQUEST_URI}`, 'Permanent', false)}`,
      '        </rule>',
      '        <!-- ==== END canonical host and HTTPS ==== -->');
  }
  push('        <rule name="DP hidden files" stopProcessing="true">',
    '          <match url="(?:^|/)\\.(?!well-known(?:/|$))" />',
    '          <action type="CustomResponse" statusCode="404" statusReason="Not Found" statusDescription="Not Found" />',
    '        </rule>');
  for (const r of oldSite(m)) {
    const [path, hash] = splitHash(r.to);
    const match = `<match url="^${xml(reEsc(r.from.slice(1)))}$" ignoreCase="false" />`;
    if (!hash) {
      push(`        <rule name="DP old ${xml(r.from)}" stopProcessing="true">`, `          ${match}`, `          ${redirect(path, type(r.status), true)}`, '        </rule>');
      continue;
    }
    push(`        <rule name="DP old ${xml(r.from)} (query)" stopProcessing="true">`, `          ${match}`,
      '          <conditions><add input="{QUERY_STRING}" pattern="^(.+)$" /></conditions>',
      `          ${redirect(`${path}?{C:1}${hash}`, type(r.status), false)}`, '        </rule>',
      `        <rule name="DP old ${xml(r.from)}" stopProcessing="true">`, `          ${match}`,
      `          ${redirect(`${path}${hash}`, type(r.status), false)}`, '        </rule>');
  }
  const langs = m.languages.length ? `(?:(?:${langAlternation(m)})/)?` : '';
  push('        <rule name="DP index pages" stopProcessing="true">',
    `          <match url="^(${langs})index$" ignoreCase="false" />`,
    `          ${redirect('/{R:1}', type(R.pageUrls.status), true)}`,
    '        </rule>');
  if (m.languages.length) {
    push('        <rule name="DP language folders" stopProcessing="true">',
      `          <match url="^(${langAlternation(m)})$" ignoreCase="false" />`,
      `          ${redirect('/{R:1}/', type(R.pageUrls.status), true)}`,
      '        </rule>');
  }
  push('        <rule name="DP page URLs without .html" stopProcessing="true">',
    `          <match url="^(${langs}(?:${pageAlternation(m)}))$" ignoreCase="false" />`,
    `          ${redirect('/{R:1}.html', type(R.pageUrls.status), true)}`,
    '        </rule>');
  if (m.platform) {
    push(`        <!-- The Peetham's existing platform → ${xml(m.platform.origin)} (${m.platform.status}) -->`,
      '        <rule name="DP platform" stopProcessing="true">',
      `          <match url="^(?:${platformAlternation(m)})(?:/.*)?$" ignoreCase="false" />`,
      `          ${redirect(`${m.platform.origin}{REQUEST_URI}`, type(m.platform.status), false)}`,
      '        </rule>',
      '        <rule name="DP platform pages" stopProcessing="true">',
      `          <match url="^(?:${prefixAlternation(m)})/." ignoreCase="false" />`,
      `          ${redirect(`${m.platform.origin}{REQUEST_URI}`, type(m.platform.status), false)}`,
      '        </rule>');
  } else {
    push('        <!-- Platform paths: none. The platform shares this host; see site.config.json. -->');
  }
  push('      </rules>',
    '    </rewrite>',
    '  </system.webServer>');
  for (const g of m.assetGroups) {
    push(`  <location path="${xml((g.dir || g.file).slice(1))}">`,
      '    <system.webServer>',
      '      <httpProtocol>',
      '        <customHeaders>',
      '          <remove name="Cache-Control" />',
      `          <add name="Cache-Control" value="${xml(g.value)}" />`,
      '        </customHeaders>',
      '      </httpProtocol>',
      '    </system.webServer>',
      '  </location>');
  }
  push('</configuration>', '');
  return L.join('\n');
}

// ---------------------------------------------------------------- Vercel ---

export function renderVercel(m) {
  const vHeaders = (o) => Object.entries(o).map(([key, value]) => ({ key, value }));
  // Vercel applies every matching rule in order; for one header the later
  // rule wins, so the specific cache rules follow the catch-all.
  const headers = [{ source: '/(.*)', headers: vHeaders({ ...m.headers, 'Cache-Control': m.defaultCache }) }];
  for (const rule of [...m.cache].reverse()) {
    headers.push({ source: `${rule.prefix}(.*)\\.(${rule.extensions.join('|')})`, headers: vHeaders({ 'Cache-Control': rule.value }) });
  }
  const redirects = m.redirects.map((r) => ({ source: r.from, destination: r.to, statusCode: r.status }));
  if (m.platform) {
    const { origin, status } = m.platform;
    for (const p of m.platform.paths) redirects.push({ source: p, destination: origin + p, statusCode: status });
    for (const p of m.platform.paths) redirects.push({ source: `${p}/:path+`, destination: `${origin}${p}/:path+`, statusCode: status });
    for (const p of m.platform.prefixes) redirects.push({ source: `${p}:path+`, destination: `${origin}${p}:path+`, statusCode: status });
  }
  return JSON.stringify({
    $schema: 'https://openapi.vercel.sh/vercel.json',
    buildCommand: 'node build.mjs',
    installCommand: 'echo no-install',
    outputDirectory: 'site',
    framework: null,
    // Canonical URLs keep .html. trailingSlash is left unset on purpose:
    // `false` would 308 /kn/ to /kn, where the page's relative links break.
    cleanUrls: false,
    headers,
    redirects,
  }, null, 2) + '\n';
}

